#!/usr/bin/env python3
"""Reproducible nondegeneracy validation for the one-dimensional cold-port adjoint.

The cold-port adjoint used in the reported calculations obeys, in the normalized leg
coordinate ``u=x/L``,

    psi_uu + c1(u) psi_u + c0(u) psi = 0,
    psi(0)=1, psi(1)=0,

where

    c1 = I_i tau L/(kappa A),
    c0 = rho_T I_i**2 L**2/(kappa A**2).

For the associated homogeneous Dirichlet problem define

    P(u)=exp(integral_0^u c1(s) ds).

Multiplication by ``P`` gives the self-adjoint form

    (P psi_u)_u + P c0 psi = 0.

The Poincare inequality proves a sufficient uniqueness condition

    eta = (Pmax/Pmin) * ||max(c0,0)||_infinity / pi**2 < 1.

Unlike a bound involving ``rho_T`` alone, ``eta`` retains the integrating
factor generated by the first-order Thomson term.  A sharper second condition
uses the Liouville substitution ``psi=exp[-A/2]z``, ``A'=c1``:

    z_uu + V z = 0,   V=c0-c1_u/2-c1**2/4.

Thus ``sup(max(V,0))/pi**2 < 1`` is also sufficient.  The script evaluates
both conditions and an independent shooting determinant on every one-dimensional
baseline used by the PbSe and BTS/BST material-system analyses, including the
published-property perturbation families and the finite-difference baselines.
The calculation is a mathematical well-posedness validation, not experimental
validation.
"""

